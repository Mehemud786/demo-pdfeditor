from fastapi import FastAPI, Form, HTTPException
from fastapi.middleware.cors import CORSMiddleware
import requests

app = FastAPI(title="Session Token Extractor")

# Allow requests from any frontend domain
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"], 
    allow_methods=["*"],
    allow_headers=["*"],
)

# NOTE: Verify the exact login path (/api/login vs /wp-login.php etc.) in your browser's Network tab
TARGET_LOGIN_URL = "https://nirnoy.smartxlab.in/public/login" 

# Health check route to verify Vercel deployment isn't returning a 404
@app.get("/")
def health_check():
    return {"status": "Backend is active. POST credentials to /api/extract-token"}

@app.post("/api/extract-token")
def extract_token(username: str = Form(...), password: str = Form(...)):
    payload = {
        "username": username,
        "password": password
    }
    
    try:
        session = requests.Session()
        response = session.post(TARGET_LOGIN_URL, data=payload)
        
        # Check if login was successful
        if response.status_code not in (200, 201, 302):
            raise HTTPException(status_code=response.status_code, detail="Authentication failed. Check credentials or endpoint.")
            
        # Extract cookies generated by the session
        extracted_cookies = session.cookies.get_dict()
        
        # Extract JSON tokens if the API returns them
        json_token = None
        if "application/json" in response.headers.get("Content-Type", ""):
            json_token = response.json().get("token", None) 

        return {
            "target": "nirnoy.smartxlab.in",
            "status_code": response.status_code,
            "session_cookies": extracted_cookies,
            "json_token": json_token,
        }
        
    except requests.exceptions.RequestException as e:
        raise HTTPException(status_code=500, detail=str(e))